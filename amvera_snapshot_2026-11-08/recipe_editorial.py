def recipes():
    for number,(title,category,meal,parts,preparation) in enumerate(_DRAFTS,466):
        ingredients=[{'product':name,'amount':grams,'unit':'г'} for name,grams in parts]
        known=all(energy(name,grams) is not None for name,grams in parts)
        yield {'id':f'R{number:04d}','title':title,'category':category,'meal':meal,
               'ingredients':ingredients,'preparation':preparation,
               'nutrition_status':'estimated_unverified' if known else 'unknown',
               'origin':'editorial_draft'}


def init(db):
    import json
    db.executemany('''INSERT OR IGNORE INTO zr_recipes
        (id,title,category,meal,ingredients_json,preparation,nutrition_status,origin)
        VALUES (?,?,?,?,?,?,?,?)''',[
        (r['id'],r['title'],r['category'],r['meal'],json.dumps(r['ingredients'],ensure_ascii=False),
         r['preparation'],r['nutrition_status'],r['origin']) for r in recipes()])
