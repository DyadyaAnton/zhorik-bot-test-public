def seed_catalog():
    with connect_db() as conn:
        conn.execute("BEGIN IMMEDIATE")
        for category, raw in CATEGORIES.items():
            for name in raw.split(";"):
                unit = "л" if name.startswith(("Молоко", "Кефир", "Ряженка", "Вода", "Сок", "Морс", "Компот", "Квас")) else ("шт" if name in ("Яйца",) else "кг")
                conn.execute("INSERT OR IGNORE INTO products(name,category,unit) VALUES (?,?,?)", (name,category,unit))

def price_coverage():
    with connect_db() as conn:
        p = conn.execute("SELECT COUNT(*) FROM products").fetchone()[0]
        n = conn.execute("SELECT COUNT(*) FROM prices").fetchone()[0]
        return p,n
