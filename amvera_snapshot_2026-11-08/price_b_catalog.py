def seeds():
    result = []
    for category, packed in GROUPS.items():
        for name in packed.split("|"):
            name = name.strip()
            if not name:
                continue
            unit = "л" if category == "Напитки и прочее" and name in ("Вода питьевая", "Вода газированная") else "кг"
            if name.startswith("Яйца "):
                unit = "шт"
            elif category == "Масла и приправы" and name.startswith("Масло "):
                unit = "л"
            elif category == "Молоко и молочные" and name.startswith(("Молоко ", "Кефир ", "Сливки ", "Ряженка", "Простокваша", "Ацидофилин", "Йогурт питьевой")):
                unit = "л"
            result.append((f"CP{len(result)+1:04d}", name, category, unit))
    normalized = [name.casefold().replace("ё", "е") for _, name, _, _ in result]
    if len(normalized) != len(set(normalized)):
        raise RuntimeError("Duplicate canonical catalog names")
    return tuple(result)
